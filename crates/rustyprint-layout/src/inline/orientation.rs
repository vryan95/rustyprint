/// Whether `c` is set upright in vertical text with `text-orientation: mixed`.
pub(crate) fn is_upright(c: char) -> bool {
    let c = u32::from(c);
    let index = UPRIGHT.partition_point(|&(_, end)| end < c);
    UPRIGHT.get(index).is_some_and(|&(start, _)| start <= c)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ideographs_and_kana_stand_upright() {
        assert!(is_upright('日'));
        assert!(is_upright('あ'));
        assert!(is_upright('カ'));
        assert!(is_upright('한'));
        assert!(is_upright('。'));
        assert!(is_upright('Ａ'));
    }

    #[test]
    fn latin_and_digits_go_sideways() {
        assert!(!is_upright('a'));
        assert!(!is_upright('1'));
        assert!(!is_upright(' '));
        assert!(!is_upright('—'));
    }

    #[test]
    fn ranges_are_sorted() {
        assert!(UPRIGHT.windows(2).all(|w| w[0].1 < w[1].0));
        assert!(UPRIGHT.iter().all(|&(start, end)| start <= end));
    }
}
